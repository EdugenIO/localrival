import {resolve} from 'node:path';
import {env} from './shims/env';
import {requestContext} from './shims/context';
import {createPool,databaseAdapter,initialize} from './postgres.mjs';
import {createAppServer} from './http.mjs';
import * as account from '../app/api/steam/account/route';
import * as start from '../app/api/steam/start/route';
import * as callback from '../app/api/steam/return/route';
import * as exchange from '../app/api/session/exchange/route';
import * as logout from '../app/api/session/logout/route';
import * as leaderboard from '../app/api/leaderboard/route';
import * as sync from '../app/api/games/sync/route';
import * as browserSync from '../app/api/dota/browser-sync/route';
import * as nightly from '../app/api/jobs/dota/route';
const origin=process.env.RUNTIME_SITE_ORIGIN||process.env.RENDER_EXTERNAL_URL;
if(!origin||new URL(origin).origin!==origin||new URL(origin).protocol!=='https:'&&process.env.NODE_ENV==='production')throw Error('A fixed HTTPS backend origin is required');
const pool=createPool(process.env.DATABASE_URL);
await initialize(pool);
env.DB=databaseAdapter(pool);
const handlers={'/api/steam/account':account,'/api/steam/start':start,'/api/steam/return':callback,'/api/session/exchange':exchange,'/api/session/logout':logout,'/api/leaderboard':leaderboard,'/api/games/sync':sync,'/api/dota/browser-sync':browserSync,'/api/jobs/dota':nightly};
const server=createAppServer({origin,handlers,runRequest:(request:Request,action:()=>Promise<Response>)=>requestContext.run(request,action),healthCheck:()=>pool.query('SELECT 1'),staticRoot:resolve('render-dist/public'),trustedProxyHops:process.env.RENDER_EXTERNAL_URL?1:0});
server.listen(Number(process.env.PORT||10000),'0.0.0.0',()=>console.log('Local Rival ready'));
process.on('SIGTERM',()=>{server.close(()=>{pool.end().finally(()=>process.exit(0))})});
